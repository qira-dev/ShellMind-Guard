pub fn find_rule_doc(id: &str) -> Option<&'static RuleDoc> {
    let q = id.trim().to_ascii_uppercase();
    RULE_CATALOG.iter().find(|r| r.rule_id == q).or_else(|| {
        RULE_CATALOG.iter().find(|r| {
            let prefix = r
                .rule_id
                .rsplit_once('-')
                .map(|(p, _)| p)
                .unwrap_or(r.rule_id);
            q.starts_with(prefix)
        })
    })
}
