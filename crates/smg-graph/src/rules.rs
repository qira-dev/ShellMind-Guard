pub fn find_rule_doc(id: &str) -> Option<&'static RuleDoc> {
    let q = id.trim().to_ascii_uppercase();
    RULE_CATALOG.iter().find(|r| r.rule_id == q).or_else(|| {
        RULE_CATALOG.iter().find(|r| {
            let prefix = r
                .rule_id
                .rsplit_once('-')
                .map(|(p, _)| p)
                .unwrap_or(r.rule_id);
            prefix != "SMG-ENG" && q.starts_with(prefix)
        })
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn test_rule_catalog_complete_and_unique() {
        let mut seen = HashSet::new();
        for doc in RULE_CATALOG {
            assert!(
                seen.insert(doc.rule_id),
                "Duplicate rule_id in RULE_CATALOG: {}",
                doc.rule_id
            );
            let resolved = find_rule_doc(doc.rule_id)
                .unwrap_or_else(|| panic!("find_rule_doc missing {}", doc.rule_id));
            assert_eq!(resolved.rule_id, doc.rule_id);
        }
        assert!(
            RULE_CATALOG.len() >= 90,
            "Expected complete synced RULE_CATALOG >= 90 rules, got {}",
            RULE_CATALOG.len()
        );
        // Verify exact resolution without cross-family aliasing bugs
        assert_eq!(find_rule_doc("SMG-ENG-INT").unwrap().rule_id, "SMG-ENG-INT");
        assert_eq!(
            find_rule_doc("SMG-ENG-LEAK").unwrap().rule_id,
            "SMG-ENG-LEAK"
        );
        assert_eq!(find_rule_doc("SMG-CFG-TLS").unwrap().rule_id, "SMG-CFG-TLS");
    }
}
